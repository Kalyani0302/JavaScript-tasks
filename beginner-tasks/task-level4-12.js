console.log(`Task 11: subtract(15, 10) = ${subtract(15, 10)}`);
console.log(`Task 11: multiply(15, 10) = ${multiply(15, 10)}`);
console.log(`Task 11: divide(15, 10) = ${divide(15, 10)}`);
